def write_mesh_quality_csv(tree: str, step: int = 0) -> Path | None:
    """Write results/99_shared/sop/<tree>_mesh_quality.csv.

    Parameters:
        tree: run folder name under results/.
        step: grid dump step to read (default 0 = full mesh).
    Returns:
        The path written, or None when no grid dump exists for this tree.
    Exceptions:
        ValueError from mesh_metrics propagates -- a degenerate mesh must not
        be published as a passing table.
    References: Standard Operating Procedure of CFD.md, Ch.5
    """
    dump = RESULTS_DIR / tree / f"grid.{step}.out"
    d = load_grid_dump(dump)
    if d is None:
        return None

    metrics = mesh_metrics(d)
    _, facts = parse_run_log(RESULTS_DIR / tree / "run.sparta.log")

    SOP_DIR.mkdir(parents=True, exist_ok=True)
    out = SOP_DIR / f"{tree}_mesh_quality.csv"
    rows: list[dict[str, object]] = []
    for key in ("skewness_min", "skewness_mean", "ortho_min", "ortho_mean",
                "aspect_ratio", "aspect_ratio_mean", "aspect_ratio_min",
                "growth_rate"):
        rows.append({
            "metric": key,
            "value": f"{metrics[key]:.9g}",
            "gate": GATES.get(_GATE_KEY.get(key, "aspect_ratio"), "report"),
            "method": "cell_bounding_box",
            "source": str(dump.relative_to(PROJECT_ROOT)),
            "note": "axis-aligned rectangle: skew=0, ortho=1 exactly (T1)",
        })
    rows.append({
        "metric": "n_cells",
        "value": str(int(metrics["n_cells"])),
        "gate": "report",
        "method": "grid_dump",
        "source": str(dump.relative_to(PROJECT_ROOT)),
        "note": "cells present in the dump",
    })
    for key in ("cells_outside_surf", "cells_inside_surf",
                "cells_overlapping_surf", "surf_cells_split",
                "flow_volume_cellwise", "flow_volume_global"):
        if key in facts:
            rows.append({
                "metric": key,
                "value": f"{facts[key]:.9g}",
                "gate": "report",
                "method": "sparta_run_log",
                "source": str((RESULTS_DIR / tree / "run.sparta.log").relative_to(PROJECT_ROOT)),
                "note": "cut-cell statistic reported by the solver",
            })
    if "flow_volume_cellwise" in facts and "flow_volume_global" in facts:
        cw, gl = facts["flow_volume_cellwise"], facts["flow_volume_global"]
        rel = abs(cw - gl) / gl if gl else float("nan")
        rows.append({
            "metric": "flow_volume_closure_rel_err",
            "value": f"{rel:.9g}",
            "gate": "<1.0e-6",
            "method": "sparta_run_log",
            "source": str((RESULTS_DIR / tree / "run.sparta.log").relative_to(PROJECT_ROOT)),
            "note": "|cell-wise - global| / global; volume-conservation check",
        })

    with out.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(f"[sop-artifacts] mesh quality -> {out.relative_to(PROJECT_ROOT)} "
          f"({len(rows)} rows)")
    return out


def write_residuals_csv(tree: str) -> Path | None:
    """Write results/99_shared/sop/<tree>_residuals.csv (SOP Ch.8 series).

    Parameters:
        tree: run folder name under results/.
    Returns:
        The path written, or None when the run log is absent.
    Exceptions:
        OSError propagates from the writer after the log is read.
    Notes:
        The `residual_kind` column records that this is a DSMC particle-count
        stationarity series, NOT a continuum residual (A4).  The GUI must not
        present it as one.
    References: Standard Operating Procedure of CFD.md, Ch.8
    """
    rows, facts = parse_run_log(RESULTS_DIR / tree / "run.sparta.log")
    if not rows:
        return None

    SOP_DIR.mkdir(parents=True, exist_ok=True)
    out = SOP_DIR / f"{tree}_residuals.csv"
    fieldnames = ["step", "cpu_s", "n_particles", "delta_particles",
                  "retention_frac", "stationarity_indicator", "residual_kind"]
    with out.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({**row,
                             "residual_kind": "dsmc_stationarity_not_continuum"})
    print(f"[sop-artifacts] residuals -> {out.relative_to(PROJECT_ROOT)} "
          f"({len(rows)} rows, particle balance "
          f"{rows[-1]['retention_frac']:.5f} of {int(facts.get('n_particles', 0))})")
    return out


# --------------------------------------------------------------------------------
# 4.  3-level grid independence (SOP Ch.6 / Ch.12#4 / Ch.15)
# --------------------------------------------------------------------------------
#  Mesh-independence tolerance on the finest-two QoI change.
#  OWNER-SET (2026-10-16, "Let's just set to 10% as threshold rather than 5%").
#  SOP Ch.6 step 4 hands this number to the study; it is not derived here.
TOLERANCE_PCT = 10.0
TOLERANCE_SOURCE = ("owner decision 2026-10-16; SOP Ch.6 step 4 leaves the "
                    "tolerance to the study")


def _observed_order(n_cells, qoi):
    """Observed order of accuracy p from three systematically refined runs.

    Solves p = ln|(f3 - f2)/(f2 - f1)| / ln(r32) with r32 the cell-count-based
    refinement ratio between the FINEST pair.  Cell counts scale with the
    square of the linear scale factor these decks refine on, so r = sqrt(N).
    Using r32 only (not the geometric mean of r21 and r32) is what keeps the
    log consistent when the three levels are NOT a constant-ratio sequence --
    and this study's are not (70 -> 100 -> 139 gives r21 = 1.4286,
    r32 = 1.3900), so the constant-ratio form of the formula cannot be used.

    Parameters:
        n_cells: cell counts in ascending order (coarse, medium, fine).
        qoi: the same quantity of interest for those three levels.
    Returns:
        Observed order p, or None when either interval's difference is zero
        (p is UNDEFINED there, not zero, and must not be reported as 0).
    Exceptions: none.
    References: SOP Ch.6 step 5 (quote the observed convergence rate);
                Celik et al., J. Fluids Eng. 130 (2008) 078001.
    """
    if len(n_cells) != 3 or len(qoi) != 3:
        return None
    if min(abs(c) for c in n_cells) <= 0.0:
        return None
    e21 = qoi[1] - qoi[0]
    e32 = qoi[2] - qoi[1]
    if e21 == 0.0 or e32 == 0.0:
        return None
    r32 = (n_cells[2] / n_cells[1]) ** 0.5
    if r32 <= 1.0:
        return None
    return math.log(abs(e32 / e21)) / math.log(r32)


def _convergence_analysis(levels):
    """GCI-style convergence evidence for the three-level study.

    Emits the observed order, a Richardson-extrapolated value on the fine
    mesh, the estimated extrapolated relative error and a fine-grid GCI, so a
    reader can judge mesh sensitivity instead of reading a bare percentage.

    Parameters:
        levels: the level records in ASCENDING n_cells order.
    Returns:
        dict of convergence evidence, or None when <3 levels or a value is
        missing -- never a fabricated number.
    Exceptions: none.
    """
    if len(levels) < 3:
        return None
    try:
        cells = [float(x["n_cells"]) for x in levels]
        qo = [float(x["qoi_value"]) for x in levels]
    except (KeyError, TypeError, ValueError):
        return None
    if any(c <= 0.0 for c in cells) or any(v == 0.0 for v in qo):
        return None

    r21 = (cells[1] / cells[0]) ** 0.5
    r32 = (cells[2] / cells[1]) ** 0.5
    note = None
    if abs(r32 - r21) > 1.0e-9:
        #  The classic GCI formula assumes a CONSTANT refinement ratio.  This
        #  study's grids are 70/100/139, which are not, so the GCI below is
        #  reported as an estimate and the ratios are stated for the reader
        #  rather than silently averaged away.
        note = (f"refinement ratios are not constant (r21={r21:.4f}, "
                f"r32={r32:.4f}); GCI is an estimate, not a bound")

    out = {
        "r21": r21,
        "r32": r32,
        "observed_order_p": _observed_order(cells, qo),
        "method": "Richardson extrapolation + GCI, Fs=1.3 (3 meshes only)",
        "citation": "Celik et al., J. Fluids Eng. 130 (2008) 078001",
        "note": note,
    }
    p = out["observed_order_p"]
    if p is None:
        out["note"] = ((out["note"] + "; ") if out["note"] else "") + (
            "observed order undefined (zero change in one interval)")
        return out
    if p <= 0.0:
        out["note"] = ((out["note"] + "; ") if out["note"] else "") + (
            "observed order <= 0: the QoI is not converging on these levels")
        return out

    denom = r32 ** p - 1.0
    if denom == 0.0:
        out["note"] = ((out["note"] + "; ") if out["note"] else "") + (
            "degenerate denominator; extrapolation not applicable")
        return out
    out["richardson_extrapolated_qoi"] = qo[2] + (qo[2] - qo[1]) / denom
    out["estimated_extrapolated_error_pct"] = 100.0 * abs((qo[2] - qo[1]) / qo[2])
    out["gci_fine_pct"] = (100.0 * 1.3 * abs((qo[2] - qo[1]) / qo[2]) / denom)
    out["factor_of_safety"] = 1.3
    return out


def _gci_vs_tolerance(conv):
    """Compare the GCI estimate against the owner's tolerance.

    The pairwise-change tolerance and a GCI discretisation-error estimate
    answer different questions.  When the pairwise test passes but the GCI
    does not, "MET" must be reported TOGETHER with that disagreement, or the
    status implies a mesh-independence claim the study has not made.

    Parameters:
        conv: the dict from _convergence_analysis (may be None or partial).
    Returns:
        dict {"ok": bool, "detail": str}.
    Exceptions: none.
    """
    if not conv or conv.get("gci_fine_pct") is None:
        return {"ok": True, "detail": "no GCI estimate available"}
    gci = float(conv["gci_fine_pct"])
    if gci <= TOLERANCE_PCT:
        return {"ok": True,
                "detail": f"GCI {gci:.2f}% is within the "
                          f"{TOLERANCE_PCT:g}% tolerance"}
    return {"ok": False,
            "detail": (f"GCI {gci:.2f}% EXCEEDS the {TOLERANCE_PCT:g}% "
                       f"tolerance: the finest-two change is inside the "
                       f"tolerance but the estimated fine-mesh discretisation "
                       f"error is not")}


def collect_grid_independence() -> Path | None:
    """Aggregate level_*.json case trees into results/99_shared/sop/.

    Parameters:
        none -- reads GRID_INDEP_DIR/level_*/case.json.
    Returns:
        Path to grid_independence.json, or None when fewer than 3 levels have
        been produced (an honest "not yet", never a fabricated delta).
    Exceptions:
        OSError/json.JSONDecodeError on one level are reported and that level
        is dropped rather than crashing the aggregator.
    References: Standard Operating Procedure of CFD.md, Ch.6, Ch.12#4, Ch.15
    """
    levels: list[dict[str, object]] = []
    if GRID_INDEP_DIR.is_dir():
        for case_json in sorted(GRID_INDEP_DIR.glob("level_*/case.json")):
            try:
                with case_json.open("r", encoding="utf-8") as fh:
                    levels.append(json.load(fh))
            except (OSError, json.JSONDecodeError) as exc:
                print(f"[sop-artifacts] skipping {case_json}: {exc}", file=sys.stderr)

    SOP_DIR.mkdir(parents=True, exist_ok=True)
    out = SOP_DIR / "grid_independence.json"

    if len(levels) < 3:
        payload = {
            "status": "NOT_MET",
            "reason": (
                f"{len(levels)} of 3 refinement levels present under "
                f"{GRID_INDEP_DIR.relative_to(PROJECT_ROOT)}/level_*; "
                "run scripts/run_grid_independence.py to emit all three"
            ),
            "levels": levels,
            "sop": "Ch.6 / Ch.12#4 / Ch.15",
        }
    else:
        ordered = sorted(levels, key=lambda x: float(x.get("n_cells", 0)))
        qo = [float(x["qoi_value"]) for x in ordered]
        deltas = [abs(qo[i] - qo[i - 1]) / abs(qo[i - 1]) * 100.0
                  for i in range(1, len(qo)) if qo[i - 1] != 0.0]
        #  TOLERANCE IS OWNER-SET, NOT PROGRAM-SET.  The SOP (Chapter 6,
        #  step 4) deliberately leaves this number to the study: "within the
        #  tolerance the study requires".  An earlier version hardcoded 5.0
        #  and labelled it `criterion`, which presented MY guess as the
        #  programme's standard -- the same class of error as quoting a
        #  percentage with no stated basis, which SOP 13.x forbids.
        #  The owner set 10 % on 2026-10-16; it is recorded as such.
        meets = bool(deltas) and deltas[-1] < TOLERANCE_PCT
        conv = _convergence_analysis(ordered)
        gci_flag = _gci_vs_tolerance(conv)
        payload = {
            "status": "MET" if meets else "NOT_MET",
            #  Three distinct reasons, because they are distinct states.
            #  Getting this wrong once made the artefact claim 7.664%
            #  exceeded a 10% tolerance -- the GCI banner was re-using the
            #  tolerance-failure text.
            "reason": (
                None if (meets and gci_flag["ok"])
                else gci_flag["detail"] if meets
                else (f"finest-two change {deltas[-1]:.3f}% exceeds the "
                      f"{TOLERANCE_PCT:g}% tolerance (QoI {qo[-2]:.6g} -> "
                      f"{qo[-1]:.6g})"
                      if deltas
                      else "no QoI values in level records")
            ),
            "levels": ordered,
            "deltas_pct": deltas,
            "tolerance_pct": TOLERANCE_PCT,
            "tolerance_source": TOLERANCE_SOURCE,
            "convergence": _convergence_analysis(ordered),
            #  The owner's tolerance is on the PAIRWISE change.  A GCI-style
            #  estimate can disagree with it, and when it does the artefact
            #  must say so rather than let "MET" imply a settled mesh.
            "gci_vs_tolerance": _gci_vs_tolerance(conv),
            "sop": "Ch.6 / Ch.12#4 / Ch.15",
        }

    out.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    print(f"[sop-artifacts] grid independence -> {out.relative_to(PROJECT_ROOT)} "
          f"({payload['status']}, {len(levels)} level(s))")
    return out


# --------------------------------------------------------------------------------
# 5.  CLI
# --------------------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    """Run the requested SOP artefact generators.

    Parameters:
        argv: argument list; defaults to sys.argv[1:].  With no flags every
              generator runs, which is what run.py relies on.
    Returns:
        0 on success, 1 when a requested generator found no source data.
    Exceptions:
        ValueError from mesh_metrics is reported as a failure, not swallowed.
    References: Standard Operating Procedure of CFD.md, Ch.5/Ch.6/Ch.8
    """
    parser = argparse.ArgumentParser(
        prog="generate_sop_artifacts",
        description="Emit numeric SOP artefacts (mesh quality, residuals, "
                    "3-level grid independence) for the sidecar GUI.")
    parser.add_argument("--trees", nargs="+", default=list(DEFAULT_TREES))
    parser.add_argument("--mesh-quality", action="store_true")
    parser.add_argument("--residuals", action="store_true")
    parser.add_argument("--grid-independence", action="store_true")
    args = parser.parse_args(argv)

    # No flag at all => run everything (the run.py default path).
    run_all = not (args.mesh_quality or args.residuals or args.grid_independence)
    run_mesh = run_all or args.mesh_quality
    run_res = run_all or args.residuals
    run_grid = run_all or args.grid_independence

    failures = 0
    if run_mesh:
        for tree in args.trees:
            try:
                if write_mesh_quality_csv(tree) is None:
                    print(f"[sop-artifacts] {tree}: no grid dump, "
                          f"mesh-quality table NOT written", file=sys.stderr)
                    failures += 1
            except ValueError as exc:
                print(f"[sop-artifacts] {tree}: {exc}", file=sys.stderr)
                failures += 1
    if run_res:
        for tree in args.trees:
            if write_residuals_csv(tree) is None:
                print(f"[sop-artifacts] {tree}: no run log, "
                      f"residual series NOT written", file=sys.stderr)
                failures += 1
    if run_grid:
        collect_grid_independence()

    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
