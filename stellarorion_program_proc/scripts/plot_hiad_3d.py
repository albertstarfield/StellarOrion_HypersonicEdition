def main() -> int:
    """
    APPLICATION:
      1. Parse .surf file from command-line arg or default path
      2. Build surface-of-revolution mesh
      3. Generate interactive HTML
      4. Print summary

    Safety fallback (code-quality.md): If file not found, print error and exit 1.
    """
    # Determine input path
    if len(sys.argv) > 1:
        surf_path = sys.argv[1]
    else:
        # Default: look for HIAD_custom.surf in project root
        script_dir = Path(__file__).resolve().parent
        surf_path = str(script_dir.parent / "HIAD_custom.surf")

    # APPLICATION STEP 1: Read the .surf file (AXIOM 1)
    try:
        profile = read_surf(surf_path)
    except FileNotFoundError:
        print(f"ERROR: Surface file not found: {surf_path}", file=sys.stderr)
        return 1
    except (OSError, ValueError) as exc:
        print(f"ERROR: Failed to read {surf_path}: {exc}", file=sys.stderr)
        return 1

    if len(profile) < 3:
        print(
            f"ERROR: Profile has only {len(profile)} points (need >= 3)",
            file=sys.stderr,
        )
        return 1

    print(f"Read {len(profile)} profile points from {surf_path}")
    print(f"  Axial range: {min(z for z, _ in profile):.6f} to "
          f"{max(z for z, _ in profile):.6f} m")
    print(f"  Radial range: {min(r for _, r in profile):.6f} to "
          f"{max(r for _, r in profile):.6f} m")

    # APPLICATION STEP 2: Build surface-of-revolution mesh (THEOREM 1)
    X, Y, Z = build_revolution_mesh(profile, N_AZIMUTHAL)
    print(f"Built revolution mesh: {N_AZIMUTHAL} x {len(profile)} = "
          f"{N_AZIMUTHAL * len(profile)} surface elements")

    # APPLICATION STEP 3: Generate interactive HTML
    output_path = str(Path(surf_path).parent / OUTPUT_HTML)
    generate_html(X, Y, Z, profile, output_path)
    print(f"\n3D model written to: {output_path}")
    print("Open in a browser to inspect the HIAD surface of revolution.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
