def require_file(path: Path) -> Path:
    """Return ``path`` if it exists, otherwise fail loudly with context.

    Parameters:
        path: the file the generator needs.

    Returns:
        The same path, unchanged.

    Raises:
        FileNotFoundError: the file is absent.
    """
    if not path.is_file():
        raise FileNotFoundError(f"required run record is missing: {path}")
    return path


def read_grid_dump(path: Path) -> tuple[np.ndarray, dict[str, object]]:
    """Parse a SPARTA ``dump 2 grid`` file into cell rectangles.

    Parameters:
        path: the grid dump written by ``dump 2 grid all``.

    Returns:
        A tuple ``(cells, meta)``.  ``cells`` is an (n, 4) float array of
        ``(zlo, rlo, zhi, rhi)`` in metres, one row per unique cell id.
        ``meta`` carries the timestep, the box bounds and the raw row count.

    Raises:
        ValueError: the file contains no parsable cells or no box bounds.
    """
    lines = require_file(path).read_text(encoding="utf-8", errors="replace").splitlines()
    meta: dict[str, object] = {}
    by_id: dict[int, tuple[float, float, float, float]] = {}

    index = 0
    total = len(lines)
    while index < total:
        stripped = lines[index].strip()
        if stripped == "ITEM: TIMESTEP":
            meta["timestep"] = int(float(lines[index + 1].strip()))
            index += 2
            continue
        if stripped == "ITEM: NUMBER OF CELLS":
            meta["rows_in_dump"] = int(lines[index + 1].strip())
            index += 2
            continue
        if stripped.startswith("ITEM: BOX BOUNDS"):
            bounds = []
            for offset in (1, 2, 3):
                parts = lines[index + offset].split()
                bounds.append(tuple(float(v) for v in parts))
            meta["box"] = bounds
            index += 4
            continue
        if stripped.startswith("ITEM: CELLS"):
            index += 1
            for raw in lines[index:]:
                fields = raw.split()
                if len(fields) < 5:
                    continue
                try:
                    cell_id = int(fields[0])
                    zlo, rlo, zhi, rhi = (float(v) for v in fields[1:5])
                except ValueError:
                    continue
                by_id[cell_id] = (zlo, rlo, zhi, rhi)
            break
        index += 1

    if not by_id:
        raise ValueError(f"no cell records parsed from {path}")
    if "box" not in meta:
        raise ValueError(f"no BOX BOUNDS section in {path}")

    cells = np.array([by_id[key] for key in sorted(by_id)], dtype=float)
    meta["unique_cells"] = len(cells)
    return cells, meta


def read_log_facts(path: Path) -> dict[str, int]:
    """Extract the cell classification SPARTA printed at start-up.

    The start-up banner reports how the child cells were classified against
    the rasterised surface, which is the only source for the solid/overlap
    counts reported on the figure.

    Parameters:
        path: the SPARTA run log.

    Returns:
        A dict with ``child_cells``, ``cells_outside``, ``cells_inside`` and
        ``cells_overlapping``.

    Raises:
        ValueError: a required banner line is absent.
    """
    text = require_file(path).read_text(encoding="utf-8", errors="replace")
    facts: dict[str, int] = {}

    match = re.search(r"Created (\d+) child grid cells", text)
    if match is None:
        raise ValueError(f"no 'Created N child grid cells' banner in {path}")
    facts["child_cells"] = int(match.group(1))

    match = re.search(r"(\d+) (\d+) (\d+) = cells outside/inside/overlapping surfs", text)
    if match is None:
        raise ValueError(f"no surface cell classification in {path}")
    facts["cells_outside"] = int(match.group(1))
    facts["cells_inside"] = int(match.group(2))
    facts["cells_overlapping"] = int(match.group(3))
    return facts


def read_freestream(path: Path) -> dict[str, float]:
    """Read the Mach number and freestream temperature of the run.

    Parameters:
        path: the ``in.hiad`` input script.

    Returns:
        A dict with ``mach`` and ``t_inf`` in kelvin.

    Raises:
        ValueError: the header comment does not carry both quantities.
    """
    text = require_file(path).read_text(encoding="utf-8", errors="replace")
    match = re.search(r"Mach\s+([0-9.E+-]+)\s*\|\s*T_inf\s*=\s*([0-9.E+-]+)\s*K", text)
    if match is None:
        raise ValueError(f"no freestream header comment in {path}")
    return {"mach": float(match.group(1)), "t_inf": float(match.group(2))}


def read_surface(path: Path) -> np.ndarray:
    """Read a SPARTA surface file through the shared project reader.

    The reader is imported from ``plot_hiad_3d`` so that this figure and
    the interactive 3-D viewer parse the surface file identically.

    Parameters:
        path: the ``HIAD_custom.surf`` file.

    Returns:
        An (n, 2) array of ``(axial, radial)`` coordinates in metres.

    Raises:
        ValueError: the surface file holds no parsable points.
    """
    require_file(path)
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    from plot_hiad_3d import read_surf  # noqa: PLC0415 - optional-at-runtime import

    points = read_surf(str(path))
    if not points:
        raise ValueError(f"no surface points parsed from {path}")
    return np.array(points, dtype=float)


def close_profile(points: np.ndarray) -> np.ndarray:
    """Close an open axisymmetric profile against the symmetry axis.

    The surface file stores an open polyline whose two ends sit on the
    symmetry axis, so appending the first point closes the body outline and
    gives a well-defined interior for the point-in-polygon test.

    Parameters:
        points: an (n, 2) array of ``(axial, radial)`` coordinates.

    Returns:
        The (n + 1, 2) closed polygon.
    """
    return np.vstack([points, points[0:1]])


def points_inside_polygon(px: np.ndarray, py: np.ndarray, polygon: np.ndarray) -> np.ndarray:
    """Ray-cast test of whether points lie inside a closed polygon.

    Parameters:
        px: x coordinates of the query points.
        py: y coordinates of the query points.
        polygon: an (n, 2) closed polygon.

    Returns:
        A boolean array, True where the point lies inside the polygon.
    """
    inside = np.zeros(px.shape, dtype=bool)
    count = len(polygon)
    j = count - 1
    for i in range(count):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        straddles = (yi > py) != (yj > py)
        dy = yj - yi
        with np.errstate(divide="ignore", invalid="ignore"):
            crossing = np.where(dy != 0.0, (xj - xi) * (py - yi) / dy + xi, xi)
        inside ^= straddles & (px < crossing)
        j = i
    return inside


def cell_edges(cells: np.ndarray) -> np.ndarray:
    """Build the unique cell-face segment set of a cell array.

    Every shared face is emitted once (AXIOM/THEORY T1), so the apparent
    line weight reports cell density instead of double-counting neighbours.

    Parameters:
        cells: an (n, 4) array of ``(zlo, rlo, zhi, rhi)``.

    Returns:
        An (m, 2, 2) array of line segments.
    """
    zlo, rlo, zhi, rhi = cells[:, 0], cells[:, 1], cells[:, 2], cells[:, 3]
    corners = np.stack(
        [
            np.stack([zlo, rlo], axis=1),
            np.stack([zhi, rlo], axis=1),
            np.stack([zhi, rhi], axis=1),
            np.stack([zlo, rhi], axis=1),
        ],
        axis=1,
    )
    segments = np.concatenate([corners, np.roll(corners, -1, axis=1)], axis=1)
    flat = segments.reshape(-1, 2, 2)
    keys = np.round(flat.reshape(-1, 4), 9)
    unique = np.unique(keys, axis=0)
    return unique.reshape(-1, 2, 2)


def draw_mesh(ax: plt.Axes, cells: np.ndarray, keep: np.ndarray) -> None:
    """Render the mesh tiles and their edges into ``ax``.

    Parameters:
        ax: the target axes.
        cells: an (n, 4) array of ``(zlo, rlo, zhi, rhi)``.
        keep: a boolean mask, True for the cells that belong to the flow
            domain (AXIOM A4).
    """
    shown = cells[keep]
    if shown.size == 0:
        raise ValueError("mesh mask removed every cell; refusing to draw an empty panel")

    zlo, rlo, zhi, rhi = shown[:, 0], shown[:, 1], shown[:, 2], shown[:, 3]
    tiles = np.stack(
        [
            np.stack([zlo, rlo], axis=1),
            np.stack([zhi, rlo], axis=1),
            np.stack([zhi, rhi], axis=1),
            np.stack([zlo, rhi], axis=1),
        ],
        axis=1,
    )
    ax.add_collection(
        PolyCollection(tiles, facecolors=CELL_FILL, edgecolors="none", zorder=1)
    )
    ax.add_collection(
        LineCollection(
            cell_edges(shown),
            colors=CELL_EDGE,
            linewidths=CELL_LW,
            capstyle="butt",
            zorder=2,
        )
    )


def draw_body(ax: plt.Axes, outline: np.ndarray, colour: str, dashed: bool) -> None:
    """Draw one body outline into ``ax``.

    Parameters:
        ax: the target axes.
        outline: the closed (n, 2) profile of the body.
        colour: the stroke colour.
        dashed: True for the optimised geometry, False for the reference.
    """
    ax.plot(
        outline[:, 0],
        outline[:, 1],
        color=colour,
        linewidth=BODY_LW,
        linestyle="--" if dashed else "-",
        solid_capstyle="round",
        dash_capstyle="round",
        zorder=4 if not dashed else 5,
    )


def style_axes(ax: plt.Axes, title: str) -> None:
    """Apply the house dark-navy style and the panel title.

    Parameters:
        ax: the axes to style.
        title: the panel title.
    """
    ax.set_facecolor(FIG_BG)
    ax.set_title(title, color=TITLE_COL, fontsize=8.5, loc="left", pad=5)
    ax.set_xlabel("Axial position z (m)", color=TEXT_COL, fontsize=8.5, labelpad=3)
    ax.set_ylabel("Radial position r (m)", color=TEXT_COL, fontsize=8.5, labelpad=3)
    for spine in ax.spines.values():
        spine.set_color(SPINE_COL)
        spine.set_linewidth(0.9)
    ax.tick_params(colors=TEXT_COL, labelsize=7.5, color=SPINE_COL, width=0.8, length=3.0)
    ax.set_aspect("equal", adjustable="box")


def main() -> int:
    """Render the mesh panel; return a process exit code.

    Returns:
        0 when the PNG was written, 1 when a run record is unusable.
    """
    try:
        cells, grid_meta = read_grid_dump(GRID_DUMP)
        log_facts = read_log_facts(RUN_LOG)
        freestream = read_freestream(RUN_INPUT)
        reference = read_surface(SURF_REFERENCE)
        optimised = read_surface(SURF_OPTIMISED)
    except (FileNotFoundError, ValueError) as exc:
        print(f"[mesh_panel] ERROR: {exc}", file=sys.stderr)
        return 1

    z_edges = np.unique(np.concatenate([cells[:, 0], cells[:, 2]]))
    r_edges = np.unique(np.concatenate([cells[:, 1], cells[:, 3]]))
    n_z = len(z_edges) - 1
    n_r = len(r_edges) - 1
    dz = float((z_edges[-1] - z_edges[0]) / n_z)
    dr = float((r_edges[-1] - r_edges[0]) / n_r)

    reference_closed = close_profile(reference)
    optimised_closed = close_profile(optimised)

    centres_z = 0.5 * (cells[:, 0] + cells[:, 2])
    centres_r = 0.5 * (cells[:, 1] + cells[:, 3])
    interior = points_inside_polygon(centres_z, centres_r, reference_closed)
    keep = ~interior

    ref_length = float(reference[:, 0].max() - reference[:, 0].min())
    opt_length = float(optimised[:, 0].max() - optimised[:, 0].min())
    ref_rmax = float(reference[:, 1].max())
    opt_rmax = float(optimised[:, 1].max())
    cells_across_z = ref_length / dz
    cells_across_r = ref_rmax / dr

    # --- figure layout: every box matches its data aspect exactly ----------
    content_w = FIG_W - MARGIN_L - MARGIN_R
    domain_w = content_w
    domain_h = domain_w * (r_edges[-1] - r_edges[0]) / (z_edges[-1] - z_edges[0])
    zoom_h = ZOOM_W * (ZOOM_R[1] - ZOOM_R[0]) / (ZOOM_Z[1] - ZOOM_Z[0])
    bottom_h = max(zoom_h, STATS_H)
    stats_w = content_w - ZOOM_W - GAP_W
    fig_h = XLABEL_BAND + bottom_h + GAP_H + domain_h + TITLE_BAND

    fig = plt.figure(figsize=(FIG_W, fig_h), dpi=300)
    fig.patch.set_facecolor(FIG_BG)

    def place(left: float, bottom: float, width: float, height: float) -> list[float]:
        """Convert an inch-space box into figure fractions."""
        return [left / FIG_W, bottom / fig_h, width / FIG_W, height / fig_h]

    ax_domain = fig.add_axes(place(MARGIN_L, XLABEL_BAND + bottom_h + GAP_H, domain_w, domain_h))
    ax_zoom = fig.add_axes(place(MARGIN_L, XLABEL_BAND, ZOOM_W, bottom_h))
    ax_stats = fig.add_axes(place(MARGIN_L + ZOOM_W + GAP_W, XLABEL_BAND, stats_w, bottom_h))

    for axes in (ax_domain, ax_zoom):
        draw_mesh(axes, cells, keep)
        draw_body(axes, reference_closed, BODY_REFERENCE, dashed=False)
        draw_body(axes, optimised_closed, BODY_OPTIMISED, dashed=True)

    # --- panel (a): full domain ------------------------------------------
    ax_domain.set_xlim(float(z_edges[0]), float(z_edges[-1]))
    ax_domain.set_ylim(float(r_edges[0]), float(r_edges[-1]))
    ax_domain.xaxis.set_major_locator(MultipleLocator(2.0))
    ax_domain.yaxis.set_major_locator(MultipleLocator(1.0))
    style_axes(ax_domain, "(a)  Full-domain Cartesian mesh")

    # --- panel (b): shoulder zoom -----------------------------------------
    ax_zoom.set_xlim(*ZOOM_Z)
    ax_zoom.set_ylim(*ZOOM_R)
    ax_zoom.xaxis.set_major_locator(MultipleLocator(0.1))
    ax_zoom.yaxis.set_major_locator(MultipleLocator(0.2))
    style_axes(ax_zoom, "(b)  Shoulder zoom")

    # --- panel (c): statistics --------------------------------------------
    ax_stats.set_facecolor(FIG_BG)
    ax_stats.set_xticks([])
    ax_stats.set_yticks([])
    for spine in ax_stats.spines.values():
        spine.set_visible(False)

    stats_lines = [
        f"MESH STATISTICS   tree {REFERENCE_TREE}, step {GRID_STEP}",
        f"  Cartesian grid             {n_z} x {n_r} x 1",
        f"  Child grid cells           {log_facts['child_cells']}",
        f"  Cell size dz / dr          {dz:.5f} / {dr:.5f} m",
        f"  Cell aspect dz / dr        {dz / dr:.2f}",
        f"  Cells across body z / r    {cells_across_z:.1f} / {cells_across_r:.1f}",
        f"  Domain z / r (m)           {z_edges[0]:.1f}..{z_edges[-1]:.1f} / "
        f"{r_edges[0]:.1f}..{r_edges[-1]:.4f}",
        f"  Cells outside surface      {log_facts['cells_outside']}",
        f"  Cells inside surface       {log_facts['cells_inside']}",
        f"  Cells overlapping surface  {log_facts['cells_overlapping']}",
        f"  Reference body  len {ref_length:.4f} m  r_max {ref_rmax:.4f} m",
        f"  Optimised body  len {opt_length:.4f} m  r_max {opt_rmax:.4f} m",
        f"  Freestream  Mach {freestream['mach']:.5f}  T_inf {freestream['t_inf']:.2f} K",
        f"  Zoom window (b)  z {ZOOM_Z[0]:.2f}..{ZOOM_Z[1]:.2f} m  "
        f"r {ZOOM_R[0]:.2f}..{ZOOM_R[1]:.2f} m",
    ]
    ax_stats.text(
        0.0,
        1.0,
        "\n".join(stats_lines),
        transform=ax_stats.transAxes,
        ha="left",
        va="top",
        color=TEXT_COL,
        fontsize=8.0,
        family="monospace",
        linespacing=1.35,
    )

    handles = [
        Line2D([0], [0], color=BODY_REFERENCE, linewidth=BODY_LW,
               label="reference body (00_reference)"),
        Line2D([0], [0], color=BODY_OPTIMISED, linewidth=BODY_LW, linestyle="--",
               label="optimised body (03_opt_geometry)"),
        Line2D([0], [0], color=CELL_EDGE, linewidth=1.2, label="Cartesian cell edges"),
    ]
    legend = ax_stats.legend(
        handles=handles,
        loc="lower left",
        bbox_to_anchor=(0.0, 0.0),
        frameon=True,
        facecolor=FIG_BG,
        edgecolor=SPINE_COL,
        framealpha=1.0,
        labelcolor=TEXT_COL,
        fontsize=8.0,
        handlelength=2.2,
        borderpad=0.5,
        labelspacing=0.45,
    )
    legend.get_frame().set_linewidth(0.8)

    fig.suptitle(
        "SPARTA computational mesh - validation reference tree 00_reference, step 2200",
        x=0.5,
        y=0.985,
        color=TITLE_COL,
        fontsize=10.0,
        fontweight="bold",
    )

    fig.savefig(OUTPUT_PNG, dpi=300, facecolor=FIG_BG, edgecolor="none")
    plt.close(fig)

    print(f"[mesh_panel] wrote {OUTPUT_PNG}")
    print(f"[mesh_panel] figure size {FIG_W:.2f} x {fig_h:.2f} in at 300 dpi")
    print(f"[mesh_panel] grid {n_z} x {n_r} x 1, {log_facts['child_cells']} child cells, "
          f"dump rows {grid_meta['rows_in_dump']}, unique {grid_meta['unique_cells']}")
    print(f"[mesh_panel] cell size dz {dz:.5f} m, dr {dr:.5f} m, aspect {dz / dr:.2f}")
    print(f"[mesh_panel] cells drawn {int(keep.sum())}, interior cells masked "
          f"{int(interior.sum())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
