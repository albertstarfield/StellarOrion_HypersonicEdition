def patch_text() -> int:
    t = CH4.read_text(encoding="utf-8")
    rc = 0
    for old, new, tag in ((OLD_P2, NEW_P2, "P2 attribution"), (OLD_P1, NEW_P1, "P1 caveat")):
        n = t.count(old)
        if n != 1:
            print(f"  !! {tag}: expected 1 match, found {n}")
            rc = 1
            continue
        t = t.replace(old, new, 1)
        print(f"  ok  {tag}")
    if rc == 0:
        CH4.write_text(t, encoding="utf-8")
    return rc


def patch_figures() -> int:
    t = MK.read_text(encoding="utf-8")
    rc = 0

    # F1 caption: drop the step-count claim, keep the stable velocity claim.
    old_note = ('    fig.text(0.5, -0.06,\n'
                '             "Runs differ by 8.4% in freestream velocity and the scalloped series ends at step 1800, not 2200.",\n'
                '             ha="center", fontsize=8, style="italic")')
    new_note = ('    fig.text(0.5, -0.06,\n'
                '             "The two runs are held at different trajectory states: freestream velocity differs by 8.4%. "\n'
                '             "Differences shown are therefore not attributable to skin geometry alone.",\n'
                '             ha="center", fontsize=8, style="italic")')
    if t.count(old_note) != 1:
        print("  !! F1 note anchor not found")
        rc = 1
    else:
        t = t.replace(old_note, new_note, 1)
        print("  ok  F1 caption note")

    # F4 legend needs an opaque background.
    old_leg = '    ax.legend(fontsize=7.5, frameon=False, loc="best")\n    fig.tight_layout()\n    save(fig, "fignew_bo_search_trace.png")'
    new_leg = ('    ax.legend(fontsize=7.5, loc="best", frameon=True, framealpha=1.0,\n'
               '               facecolor="white", edgecolor="0.7")\n'
               '    fig.tight_layout()\n'
               '    save(fig, "fignew_bo_search_trace.png")')
    if t.count(old_leg) != 1:
        print("  !! F4 legend anchor not found")
        rc = 1
    else:
        t = t.replace(old_leg, new_leg, 1)
        print("  ok  F4 opaque legend background")

    # F4 the running-minimum line crossed the optimum star: draw the star last,
    # on top, with a contrasting edge so it reads through the line.
    old_star = ('    ax.plot([idx[best_at]], [cost[best_at]], "*", ms=15, color=CB[4],\n'
                '            label=f"Optimum: index {best_at}, cost = {cost[best_at]:.4f}")')
    new_star = ('    # Drawn after the running-minimum line and with a high zorder plus a\n'
                '    # contrasting edge: previously the line ran straight through the star\n'
                '    # and the marker lost its emphasis.\n'
                '    ax.plot([idx[best_at]], [cost[best_at]], "*", ms=17, color=CB[4],\n'
                '            mec="black", mew=0.9, zorder=6,\n'
                '            label=f"Optimum: index {best_at}, cost = {cost[best_at]:.4f}")')
    if t.count(old_star) != 1:
        print("  !! F4 star anchor not found")
        rc = 1
    else:
        t = t.replace(old_star, new_star, 1)
        print("  ok  F4 optimum star zorder and edge")

    # F4 also: raise the running-minimum line's zorder below the star.
    t = t.replace('ax.semilogy(idx, running, "-", lw=1.8, color=CB[2], label="Running minimum (incumbent)")',
                  'ax.semilogy(idx, running, "-", lw=1.8, color=CB[2], zorder=3,\n'
                  '                label="Running minimum (incumbent)")')

    if rc == 0:
        MK.write_text(t, encoding="utf-8")
    return rc


def main() -> int:
    print("Chapter 4 text:")
    a = patch_text()
    print("\nFigure script:")
    b = patch_figures()
    return a or b


if __name__ == "__main__":
    raise SystemExit(main())
