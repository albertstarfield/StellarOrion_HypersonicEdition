# --------------------------------------------------------------------------------
# 1.  Grid dump parsing (A2)
# --------------------------------------------------------------------------------
def load_grid_dump(path: Path) -> dict[str, object] | None:
    """Read a SPARTA `dump ... grid` file into numeric columns.

    Parameters:
        path: Path to a grid.N.out dump written with
              `id xlo ylo xhi yhi ...`.
    Returns:
        dict with keys xlo/xhi/ylo/yhi (float arrays) and n_cells, or None
        when the file is absent or contains no data rows.
    Exceptions:
        OSError is caught and reported; a malformed row is skipped, never
        coerced to zero.
    References: SPARTA dump command, https://github.com/sparta/sparta/wiki
    """
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError as exc:
        print(f"[sop-artifacts] cannot read {path}: {exc}", file=sys.stderr)
        return None

    start = -1
    for idx, line in enumerate(lines):
        if line.startswith("ITEM: CELLS"):
            start = idx + 1
            break
    if start < 0:
        print(f"[sop-artifacts] {path.name}: no 'ITEM: CELLS' section", file=sys.stderr)
        return None

    xlo: list[float] = []
    ylo: list[float] = []
    xhi: list[float] = []
    yhi: list[float] = []
    for line in lines[start:]:
        if line.startswith("ITEM:"):
            break
        parts = line.split()
        # Need at least: id xlo ylo xhi yhi
        if len(parts) < 5:
            if line.strip():
                print(f"[sop-artifacts] {path.name}: short row skipped", file=sys.stderr)
            continue
        try:
            xlo.append(float(parts[1]))
            ylo.append(float(parts[2]))
            xhi.append(float(parts[3]))
            yhi.append(float(parts[4]))
        except ValueError:
            print(f"[sop-artifacts] {path.name}: non-numeric row skipped", file=sys.stderr)

    if not xlo:
        return None
    return {"xlo": xlo, "ylo": ylo, "xhi": xhi, "yhi": yhi, "n_cells": len(xlo)}


# --------------------------------------------------------------------------------
# 2.  Mesh quality (T1, T2)
# --------------------------------------------------------------------------------
def mesh_metrics(d: dict[str, object]) -> dict[str, float]:
    """Compute SOP Ch.5 mesh-quality metrics from cell bounding boxes.

    Parameters:
        d: dict returned by load_grid_dump (xlo/xhi/ylo/yhi lists).
    Returns:
        Mapping metric-name -> value for skewness, orthogonal quality,
        aspect ratio and growth rate.
    Exceptions:
        ValueError if a cell has zero width or height (degenerate geometry).
    Notes:
        Skewness 0 and ortho 1 are the exact values for an axis-aligned
        rectangle (T1); the growth rate is the largest ratio between
        consecutive distinct spacings along either axis.
    References: Standard Operating Procedure of CFD.md, Ch.5
    """
    xlo = d["xlo"]
    ylo = d["ylo"]
    xhi = d["xhi"]
    yhi = d["yhi"]
    assert isinstance(xlo, list) and isinstance(yhi, list)

    widths = [hi - lo for lo, hi in zip(xlo, xhi)]
    heights = [hi - lo for lo, hi in zip(ylo, yhi)]
    if any(w <= 0.0 for w in widths) or any(h <= 0.0 for h in heights):
        raise ValueError("degenerate cell: non-positive width/height")

    aspects = [max(w, h) / min(w, h) for w, h in zip(widths, heights)]

    # Consecutive-ratio growth over the distinct spacings on each axis.
    def _growth(values: list[float]) -> float:
        uniq = sorted({round(v, 12) for v in values})
        if len(uniq) < 2:
            return 1.0
        return max(b / a for a, b in itertools.pairwise(uniq) if a > 0.0)

    growth = max(_growth(widths), _growth(heights))

    return {
        "skewness_min": 0.0,
        "skewness_mean": 0.0,
        "ortho_min": 1.0,
        "ortho_mean": 1.0,
        "aspect_ratio": max(aspects),
        "aspect_ratio_mean": sum(aspects) / len(aspects),
        "aspect_ratio_min": min(aspects),
        "growth_rate": growth,
        "n_cells": float(len(aspects)),
    }


_LOG_PATTERNS = {
    # `  18746 430 145 = cells outside/inside/overlapping surfs`
    #   -> outside / inside / overlapping.  The three counts are positional;
    #      capturing the first one and calling it "overlapping" would publish
    #      a wrong number under the right name.
    "cells_outside_surf": re.compile(r"^(\d+)\s+(\d+)\s+(\d+)\s+=\s+cells outside"),
    "cells_inside_surf": re.compile(r"^(\d+)\s+(\d+)\s+(\d+)\s+=\s+cells outside"),
    "cells_overlapping_surf": re.compile(r"^(\d+)\s+(\d+)\s+(\d+)\s+=\s+cells outside"),
    # SPARTA prints `144 1 = surf cells with ...` in one tree and
    # `142 = surf cells with ...` in the other.  The trailing count is
    # optional, so the group after the first number must be too.
    "surf_cells_split": re.compile(r"^(\d+)(?:\s+\d+)?\s+=\s+surf cells with"),
    "flow_volume": re.compile(
        r"^([0-9.eE+-]+)\s+([0-9.eE+-]+)\s+=\s+cell-wise and global flow volume"
    ),
    "n_child_cells": re.compile(r"^Created (\d+) child grid cells"),
    "n_particles": re.compile(r"^Created (\d+) particles$"),
}
"""Expected SPARTA log facts, keyed by the metric name they become."""

_LOG_GROUPS = {
    "cells_outside_surf": 1,
    "cells_inside_surf": 2,
    "cells_overlapping_surf": 3,
    "surf_cells_split": 1,
    "n_child_cells": 1,
    "n_particles": 1,
}
"""1-based regex group carrying the value for each single-valued metric."""


def parse_run_log(path: Path) -> tuple[list[dict[str, float]], dict[str, float]]:
    """Read the `Step CPU Np` table and the volume/particle summary lines.

    Parameters:
        path: SPARTA run log (A3).
    Returns:
        (rows, facts).  rows is one dict per printed step with step, cpu_s,
        n_particles, delta and retention.  facts holds the geometry and
        volume-closure numbers used by the mass-balance report.
    Exceptions:
        OSError caught; a malformed table line is skipped, never zero-filled.
    References: Standard Operating Procedure of CFD.md, Ch.8
    """
    rows: list[dict[str, float]] = []
    facts: dict[str, float] = {}
    matched: set[str] = set()
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        print(f"[sop-artifacts] cannot read {path}: {exc}", file=sys.stderr)
        return rows, facts

    in_table = False
    prev_np: int | None = None
    np0: int | None = None
    step_re = re.compile(r"^\s*(\d+)\s+([0-9.eE+-]+)\s+(\d+)\s*$")
    for line in text.splitlines():
        if line.startswith("Step CPU Np"):
            in_table = True
            continue
        if in_table:
            m = step_re.match(line)
            if not m:
                if line.strip():
                    in_table = False
                continue
            step, cpu, np_now = int(m.group(1)), float(m.group(2)), int(m.group(3))
            if np0 is None:
                np0 = np_now
            delta = 0 if prev_np is None else np_now - prev_np
            rel = 0.0 if (prev_np in (None, 0)) else abs(np_now - prev_np) / prev_np
            rows.append({
                "step": float(step),
                "cpu_s": cpu,
                "n_particles": float(np_now),
                "delta_particles": float(delta),
                "retention_frac": (np_now / np0) if np0 else float("nan"),
                "stationarity_indicator": rel,
            })
            prev_np = np_now
            continue

        for key, pat in _LOG_PATTERNS.items():
            m = pat.match(line.strip())
            if not m:
                continue
            if key == "flow_volume":
                facts["flow_volume_cellwise"] = float(m.group(1))
                facts["flow_volume_global"] = float(m.group(2))
            else:
                facts[key] = float(m.group(_LOG_GROUPS[key]))
            matched.add(key)

    # A1: an expected fact that never appeared is reported, not left as an
    # absent key that a caller would silently skip over.
    missing = sorted(set(_LOG_PATTERNS) - matched)
    if missing:
        print(f"[sop-artifacts] {path.name}: no match for {', '.join(missing)}",
              file=sys.stderr)

    return rows, facts


