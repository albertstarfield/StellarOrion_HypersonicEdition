#!/usr/bin/env python3
"""High-contrast two-panel render of the SPARTA computational mesh.

PURPOSE
    The previous ``mesh_statistics_smooth.png`` drew hollow cell rectangles
    in #252F43 on a #0F172A background (contrast 1.35:1, i.e. invisible), had
    no axis labels, collided T1..T7 surface labels, buried the body outline
    under torus markers, used near-black spines and wasted ~10% of the canvas
    on dead margin.  This generator replaces it with a figure that a reader
    can actually use:

        (a) the full-domain Cartesian mesh of the validation reference tree
            ``00_reference`` at step 2200, and
        (b) a zoom on the shoulder of the reference aeroshell, where the
            discrete cell structure around the surface is resolved.

    Both panels carry the *same* cell-size statement, so the two views are
    directly comparable, and a statistics block reports the numbers the
    previous caption had to apologise for not containing.

AXIOMS
    A1.  The mesh is exactly what SPARTA wrote to
        ``results/00_reference/grid.2200.out``; every number on the figure is
        parsed from a run record, none is typed in by hand.
    A2.  The dump is a ``dump 2 grid`` of an *orthogonal Cartesian* grid, so
        the dump's first spatial column is the axial coordinate and the second
        is the radial coordinate.  This is fixed by the run input
        ``in.hiad``: ``create_box -5 9 0 3.9375 -0.5 0.5`` puts the axial
        axis on [-5, 9] m and the radial axis on [0, 3.9375] m, and the
        surface file places the body at axial 8.6e-5..1.2694 m, radial
        0..1.8802 m, which only fits that assignment.
    A3.  A cell id identifies a cell.  The dump of this run repeats id 9096
        (SPARTA wrote the row twice), so the parser keys cells by id; the
        figure reports the de-duplicated child-cell count, which is the
        number SPARTA itself printed at start-up.
    A4.  The Cartesian grid is not body-fitted: the surface is rasterised
        through a subset of the cells and the cells interior to the surface
        are not part of the flow domain.  Those interior cells are left
        blank in both panels so the two body outlines stay legible.
    A5.  A missing or unparsable run record is a loud failure, never a
        silently blank panel and never a guessed number.

THEORIES
    T1.  Drawing the cells as a de-duplicated edge set makes each shared
        cell face appear exactly once, so the apparent line weight of the
        mesh reports the local cell density instead of double-counting
        neighbours.
    T2.  Because the grid is uniform, the aspect ratio of a cell in the
        figure equals the aspect ratio of the cell in the simulation; the
        axes are therefore drawn with an equal data aspect, and the panels
        are laid out at the data aspect so no dead margin remains.
    T3.  The radial spacing is 3.56 times finer than the axial spacing, so
        the shoulder zoom resolves the surface with 12.6 cells along the
        body and 66.4 cells across its radius.  Those are the numbers the
        statistics block reports.

APPLICATIONS
    Chapter 4, Section 4.6 (mesh quality statistics): figure
    ``figures/mesh_statistics_smooth.png``, regenerated by this script from
    the validation reference run.

CITATIONS
    [1] Bird, G.A. (1994) Molecular Gas Dynamics, Oxford University Press --
        the DSMC solver whose grid is drawn here.
    [2] SPARTA DSMC solver, ``dump grid`` output format (id xlo ylo xhi yhi
        per cell) and ``read_surf`` surface-file format; the surface reader
        is reused from ``stellarorion_program_proc/scripts/plot_hiad_3d.py``
        so that this figure and the 3-D viewer cannot disagree.
    [3] Matplotlib 3.11 -- ``PolyCollection``/``LineCollection`` for bulk
        cell rendering, ``Axes.set_aspect('equal')`` for T2.

Outputs
    Lost+Found/ProgressReport/CurrentThesisFinalReport/figures/
    mesh_statistics_smooth.png   (2160 x 1788 px, dpi 300, no transparent
    padding)
"""

