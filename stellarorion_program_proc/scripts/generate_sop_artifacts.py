#!/usr/bin/env python3
"""Emit the numeric SOP artefacts the sidecar GUI honestly reports as missing.

AXIOMS
  A1.  Every number this module writes must be DERIVED from a file that is
       actually on disk.  A metric whose source cannot be read is reported as
       a status string, never as 0.0 or as a plausible-looking value.
  A2.  `results/<tree>/grid.0.out` is a real SPARTA grid dump with per-cell
       `id xlo ylo xhi yhi` plus fix columns; it is the only machine-readable
       geometry this checkout carries.
  A3.  `results/<tree>/run.sparta.log` carries the `Step CPU Np` table that
       SPARTA prints every run; it is the only solver time series here.
  A4.  DSMC is a particle method: it has no continuum residual.  Reporting a
       fabricated residual to satisfy a GUI field would be worse than the
       honest string the field already holds today.

THEORIES
  T1.  Mesh quality from cell bounding boxes.  `create_grid` builds an
       orthogonal Cartesian mesh, so every cell is an axis-aligned rectangle:
       its four corner angles are right angles, hence skewness = 0 and
       orthogonal quality = 1 exactly, and the neighbour size ratio (growth)
       is 1 for uniform spacing.  Cells clipped by the HIAD surface keep their
       Cartesian parent box in the dump, so the true cut-cell polygon is NOT
       recoverable from this file -- the method column says so rather than
       implying the box is the polygon.
  T2.  Aspect ratio = max(w,h)/min(w,h) per cell; w = xhi-xlo, h = yhi-ylo.
  T3.  Particle balance: retention = Np(k)/Np(0) and the per-interval
       stationarity indicator = |Np(k)-Np(k-1)|/Np(k-1).  Both are exact
       arithmetic on integers SPARTA printed.

APPLICATIONS
  -  `--mesh-quality`  -> results/99_shared/sop/<tree>_mesh_quality.csv
  -  `--residuals`     -> results/99_shared/sop/<tree>_residuals.csv
  -  `--grid-independence` -> results/99_shared/sop/grid_independence.json
  All three run with no arguments (default), which is how run.py Phase 2c
  gets them "generated by default".

References:
    - Standard Operating Procedure of CFD.md, Ch.5 (mesh quality),
      Ch.6/Ch.12#4/Ch.15 (3-level mesh independence), Ch.8 (convergence)
    - SPARTA dump command syntax: https://github.com/sparta/sparta/wiki
    - RFC 4180 (CSV format), https://www.rfc-editor.org/rfc/rfc4180
"""

