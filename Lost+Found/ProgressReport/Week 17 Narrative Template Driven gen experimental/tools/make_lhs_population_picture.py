"""Draw the Latin hypercube seed of the campaign's genetic algorithm.

WHY: the deck and the thesis both claim that the population of the genetic
algorithm is seeded by a Latin hypercube, and until now neither carried a
figure of it. The 50 individuals are regenerated by the real Ada seeding
path (dump_lhs.adb: Reset(Gen, 42) followed by the same Fisher-Yates and
LHS_Sample order that stellarorion_optimization.adb uses) and written to
tools/data/lhs_population_seed42_pop50.jsonl. The same population was then
proven to be the campaign's own: a run of bin/stellarorion_ga_runner with
--population 50 --generations 1 --seed 42 reproduces the recorded generation-0
winner bit for bit (cost 4.21415042877197, R_N 1.33865749835968,
r_tor 0.179613962769508, half_cone_deg 58.2918434143066) and that winner is
member i=24 of the dumped 50.

The picture therefore shows two things only, both of them true of the data:
the stratification of the three analytic coordinates, and the two pairwise
projections with the verified winner marked. The cost of the other 49
individuals is deliberately NOT drawn: the campaign ranked them under
J(x) + a linear response-surface model-fidelity penalty, which is not
exposed for a re-evaluation, so a cost-coloured figure could not be
reproduced and would be a guess.

The drawing itself lives in DRIVER and runs under the interpreter of the
thesis, which is the interpreter that already holds matplotlib; the project
virtual environment must not be polluted. This file therefore imports no
plotting library, which is also what keeps the ruff and pyrefly gates of the
deck clean.

The script writes only into the figures folder of the deck.

Citations:
    Matplotlib 3.11.2, https://matplotlib.org/stable/api/_as_gen/matplotlib.axes.Axes.scatter.html
    Matplotlib 3.11.2, https://matplotlib.org/stable/api/_as_gen/matplotlib.axes.Axes.axvline.html
    Pillow 12, https://pillow.readthedocs.io/en/stable/handbook/image-file-formats.html
"""

from __future__ import annotations

import subprocess  # ruff: ignore[suspicious-subprocess-import]
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
REPO = PROJECT.parents[2]
FIGURES = PROJECT / "figures"
VENV_PYTHON = REPO / "Lost+Found/ProgressReport/CurrentThesisFinalReport/.venv-pdf/bin/python"

#: The regenerated population, written by dump_lhs.adb.
DATA = PROJECT / "tools" / "data" / "lhs_population_seed42_pop50.jsonl"

#: The picture this script writes, in the naming convention of the deck.
OUT_PICTURE = FIGURES / "thesis_lhs_initial_population.png"

#: The member of the population that the runner proved to be the recorded
#: generation-0 winner (see the module docstring).
WINNER_ID = 24

#: A picture below this size in bytes was not written properly.
MIN_PICTURE_BYTES = 5000
#: Dots per inch of the raster, so a 7.70 in picture is 2310 px wide.
DPI = 300

#: The drawing program. It is run as a script by the interpreter of the
#: thesis, because that is where matplotlib lives.
DRIVER = r'''
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
from matplotlib import pyplot as plt
from PIL import Image

DATA = Path(sys.argv[1])
OUT = Path(sys.argv[2])
WINNER_ID = int(sys.argv[3])
MIN_BYTES = int(sys.argv[4])
DPI = int(sys.argv[5])

# Drawn at the shape of the picture box of a side_points frame:
# SIDE_POINTS_PICTURE_WIDTH_IN wide and about 4.0 in tall once the caption
# has been taken from the 4.46 in of panel, so it lands at scale 1.0.
W_IN, H_IN = 7.70, 3.98

POP = 50
C_POINT = "#0077BB"
C_WINNER = "#CC3311"
C_GRID = "#C9D3E1"
C_EDGE = "#8FA2BC"
C_TEXT = "#101820"
PT_LANE = 10.5
PT_LABEL = 9.5
PT_TITLE = 11.0

# The three coordinates of the analytic design box, with the gene that
# produces each one and its bounds from stellarorion_optimization.ads.
# R_N = Diameter_M / 2, r_tor = Toroid_Radius_M, half_cone = Angle_Deg
# (stellarorion_optimization.adb, mapping comment of SBO_Fitness).
LANES = [
    ("R_N (m)", "Diameter_M", 0.25, 7.5),
    ("r_tor (m)", "Toroid_Radius_M", 0.01, 0.5),
    ("half_cone (deg)", "Angle_Deg", 40.0, 80.0),
]


def load():
    """Read the regenerated population.

    Returns:
        list: one dict per individual, sorted by the identifier.

    Raises:
        SystemExit: When the file is missing, short or not 50 individuals.
    """
    rows = []
    for line in DATA.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    if len(rows) != POP:
        sys.stderr.write("MISMATCH expected " + str(POP) + " individuals, got "
                         + str(len(rows)) + "\n")
        raise SystemExit(1)
    return rows


def save(figure, what):
    """Write a figure and fail loudly when the picture is not a real one."""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(OUT, dpi=DPI, facecolor="white")
    size = OUT.stat().st_size if OUT.is_file() else 0
    if size < MIN_BYTES:
        sys.stderr.write("MISMATCH " + what + " was not written: "
                         + str(size) + " bytes in " + str(OUT) + "\n")
        raise SystemExit(1)
    with Image.open(OUT) as image:
        width, height = image.size
    return "[ok] " + what + ": " + str(width) + "x" + str(height) + "px, " + str(size) + " bytes"


rows = load()
r_n = [row["Diameter_M"] / 2.0 for row in rows]
r_tor = [row["Toroid_Radius_M"] for row in rows]
cone = [row["Angle_Deg"] for row in rows]
winner = next(k for k, row in enumerate(rows) if row["i"] == WINNER_ID)

figure = plt.figure(figsize=(W_IN, H_IN))

# ------------------------------------------------------------------
# Top band: the stratification of the three analytic coordinates.
# WHY: the Latin property is "exactly one individual per stratum of every
# coordinate", so the strata are drawn as columns and each individual sits
# inside the column its own value landed in. One dot per column, per lane,
# is the claim made in words on the slide, shown rather than asserted.
# ------------------------------------------------------------------
lane_axis = figure.add_axes([0.19, 0.585, 0.79, 0.335])
lane_axis.set_xlim(0.0, 1.0)
lane_axis.set_ylim(-0.6, 2.6)
for stratum in range(POP):
    lane_axis.axvline(stratum / POP, color=C_GRID, linewidth=0.4, zorder=0)
for index, (name, gene, low, high) in enumerate(LANES):
    lane = 2 - index
    values = [row[gene] / 2.0 if gene == "Diameter_M" else row[gene] for row in rows]
    norm = [(value - low) / (high - low) for value in values]
    lane_axis.scatter(
        norm, [lane] * len(norm), s=14, color=C_POINT,
        edgecolor="white", linewidth=0.4, zorder=3,
    )
    lane_axis.text(
        -0.015, lane, name + "\n[" + f"{low:g}" + ", " + f"{high:g}" + "]",
        transform=lane_axis.get_yaxis_transform(), ha="right", va="center",
        fontsize=PT_LABEL, color=C_TEXT,
    )
lane_axis.set_yticks([])
lane_axis.set_xticks([0.0, 0.25, 0.5, 0.75, 1.0])
lane_axis.set_xticklabels(["0", "0.25", "0.5", "0.75", "1.0"], fontsize=PT_LABEL)
lane_axis.set_xlabel("position inside the gene bounds, 50 strata", fontsize=PT_LABEL)
lane_axis.set_title(
    "Latin hypercube seed: one individual in every stratum of every coordinate",
    fontsize=PT_TITLE, color=C_TEXT, pad=6,
)
for spine in ("top", "right", "left"):
    lane_axis.spines[spine].set_visible(False)
lane_axis.spines["bottom"].set_color(C_EDGE)

# ------------------------------------------------------------------
# Bottom band: the two pairwise projections, with the verified winner.
# WHY the cost is not encoded: only the winner's fitness is on the record,
# so colouring by cost would invent 49 values the campaign never published.
# ------------------------------------------------------------------
panels = [
    ([0.085, 0.125, 0.38, 0.325], r_n, r_tor, "R_N (m)", "r_tor (m)"),
    ([0.585, 0.125, 0.395, 0.325], r_n, cone, "R_N (m)", "half_cone (deg)"),
]
for rect, xs, ys, xlab, ylab in panels:
    axis = figure.add_axes(rect)
    axis.scatter(
        xs, ys, s=18, color=C_POINT, edgecolor="white",
        linewidth=0.5, zorder=3,
    )
    axis.scatter(
        [xs[winner]], [ys[winner]], s=170, marker="*",
        color=C_WINNER, edgecolor="white", linewidth=0.6, zorder=4,
    )
    axis.annotate(
        "gen-0 winner",
        xy=(xs[winner], ys[winner]), xytext=(6, 6),
        textcoords="offset points", fontsize=PT_LABEL,
        color=C_WINNER, weight="bold",
    )
    axis.set_xlabel(xlab, fontsize=PT_LABEL)
    axis.set_ylabel(ylab, fontsize=PT_LABEL)
    axis.tick_params(labelsize=PT_LABEL)
    axis.grid(color=C_GRID, linewidth=0.5)
    axis.set_axisbelow(True)
    for spine in ("top", "right"):
        axis.spines[spine].set_visible(False)
    for spine in ("left", "bottom"):
        axis.spines[spine].set_color(C_EDGE)

report = save(figure, "lhs initial population")
plt.close(figure)
sys.stdout.write(report + "\n")
'''


def render() -> int:
    """Run the drawing program under the interpreter of the thesis.

    Returns:
        The exit code of the drawing program.
    """
    completed = subprocess.run(  # ruff: ignore[subprocess-without-shell-equals-true]
        [
            str(VENV_PYTHON),
            "-c",
            DRIVER,
            str(DATA),
            str(OUT_PICTURE),
            str(WINNER_ID),
            str(MIN_PICTURE_BYTES),
            str(DPI),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    _ = sys.stdout.write(completed.stdout)
    if completed.returncode != 0:
        _ = sys.stderr.write(f"MISMATCH the LHS picture failed:\n{completed.stderr[-2000:]}\n")
        return 1
    return 0


def main() -> int:
    """Draw the Latin hypercube seed picture and report what was written.

    Returns:
        Zero when the picture was written, one when the interpreter, the
        regenerated population or a source picture was missing.
    """
    if not VENV_PYTHON.is_file():
        _ = sys.stdout.write(f"MISMATCH the interpreter of the thesis is missing: {VENV_PYTHON}\n")
        return 1
    if not DATA.is_file():
        _ = sys.stdout.write(f"MISMATCH the regenerated population is missing: {DATA}\n")
        return 1
    return render()


if __name__ == "__main__":
    raise SystemExit(main())
